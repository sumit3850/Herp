// Generates assets/icons.js (Lucide icons, ISC licence) for the plain-HTML pages.
// Usage: node scripts/build-icons.mjs <path-to-lucide-static/icons>
import { readFileSync, writeFileSync } from 'node:fs';
const dir = process.argv[2];
const NAMES = ['book-open', 'scan-search', 'clipboard-list', 'route', 'user', 'triangle-alert', 'skull', 'circle-check', 'lock', 'lock-open', 'search', 'map', 'map-pin',
  'camera', 'download', 'smartphone', 'share', 'square-plus', 'x', 'check', 'eye', 'eye-off', 'chevron-right', 'leaf', 'shield-check', 'binoculars', 'layers',
  'cloud-off', 'refresh-cw', 'log-out', 'settings', 'chart-column', 'list-checks', 'sun', 'moon', 'sunset', 'info', 'printer', 'plus', 'trash-2', 'play', 'square',
  'file-down', 'badge-check', 'shopping-bag', 'mail', 'layout-dashboard', 'locate-fixed', 'timer', 'footprints', 'car', 'flag', 'arrow-right', 'monitor-smartphone'];
const out = {};
for (const n of NAMES) {
  const svg = readFileSync(`${dir}/${n}.svg`, 'utf8');
  out[n] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').trim();
}
writeFileSync(new URL('../assets/icons.js', import.meta.url), `/* Lucide icons (https://lucide.dev), ISC licence. GENERATED by scripts/build-icons.mjs */
(function (root) {
  const P = ${JSON.stringify(out)};
  root.HWI = (name, cls = '') => \`<svg class="ic \${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${P[name] || ''}</svg>\`;
})(window);
`);
console.log('icons.js:', Object.keys(out).length, 'icons');
